_RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]


def _xtime(a):
    # type: (int) -> int
    a <<= 1
    if a & 0x100:
        a ^= 0x11B
    return a & 0xFF


def _gmul(a, b):
    # type: (int, int) -> int
    res = 0
    for _ in range(8):
        if b & 1:
            res ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return res


def _key_expansion(key):
    # type: (bytes) -> tuple
    nk = len(key) // 4
    if nk not in (4, 6, 8):
        raise ValueError("invalid AES key length: {} bytes".format(len(key)))
    nr = nk + 6
    nb = 4
    w = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, nb * (nr + 1)):
        temp = list(w[i - 1])
        if i % nk == 0:
            temp = temp[1:] + temp[:1]
            temp = [_SBOX[b] for b in temp]
            temp[0] ^= _RCON[i // nk - 1]
        elif nk > 6 and i % nk == 4:
            temp = [_SBOX[b] for b in temp]
        w.append([w[i - nk][j] ^ temp[j] for j in range(4)])
    return w, nr


def _add_round_key(state, w, rnd):
    # type: (List[int], list, int) -> None
    for c in range(4):
        for r in range(4):
            state[r + 4 * c] ^= w[rnd * 4 + c][r]


def _sub_bytes(state):
    # type: (List[int]) -> None
    for i in range(16):
        state[i] = _SBOX[state[i]]


def _shift_rows(state):
    # type: (List[int]) -> None
    new = state[:]
    for r in range(4):
        for c in range(4):
            new[r + 4 * c] = state[r + 4 * ((c + r) % 4)]
    state[:] = new


def _mix_columns(state):
    # type: (List[int]) -> None
    for c in range(4):
        a0, a1, a2, a3 = (state[r + 4 * c] for r in range(4))
        state[0 + 4 * c] = _gmul(a0, 2) ^ _gmul(a1, 3) ^ a2 ^ a3
        state[1 + 4 * c] = a0 ^ _gmul(a1, 2) ^ _gmul(a2, 3) ^ a3
        state[2 + 4 * c] = a0 ^ a1 ^ _gmul(a2, 2) ^ _gmul(a3, 3)
        state[3 + 4 * c] = _gmul(a0, 3) ^ a1 ^ a2 ^ _gmul(a3, 2)


def _aes_encrypt_block(block, w, nr):
    # type: (bytes, list, int) -> bytes
    state = list(block)
    _add_round_key(state, w, 0)
    for rnd in range(1, nr):
        _sub_bytes(state)
        _shift_rows(state)
        _mix_columns(state)
        _add_round_key(state, w, rnd)
    _sub_bytes(state)
    _shift_rows(state)
    _add_round_key(state, w, nr)
    return bytes(state)


def pkcs7_pad(data, block_size=16):
    # type: (bytes, int) -> bytes
    pad = block_size - (len(data) % block_size)
    return data + bytes([pad]) * pad


def aes_cbc_encrypt(data, key, iv):
    # type: (bytes, bytes, bytes) -> bytes
    """AES-CBC 加密（PKCS7 填充），返回密文。"""
    if len(iv) != 16:
        raise ValueError("iv must be 16 bytes")
    w, nr = _key_expansion(key)
    padded = pkcs7_pad(data, 16)
    prev = iv
    out = bytearray()
    for i in range(0, len(padded), 16):
        block = bytes(a ^ b for a, b in zip(padded[i:i + 16], prev))
        enc = _aes_encrypt_block(block, w, nr)
        out += enc
        prev = enc
    return bytes(out)


def random_str(chars, length):
    # type: (str, int) -> str
    """从给定字符集中安全随机抽取 length 个字符。"""
    return "".join(secrets.choice(chars) for _ in range(length))


def timestamp_ms():
    # type: () -> int
    """返回毫秒级时间戳（与 Go 版 GetTimestamp(13) 一致）。"""
    return int(time.time() * 1000)
